// Writes packages/ledger/src/keepkill/rules.generated.ts from content/governance/keepkill-rules.yaml.
//
//   node packages/ledger/scripts/build-rules.ts           write the module
//   node packages/ledger/scripts/build-rules.ts --check   exit 1 when the module differs from a fresh generation
//
// The rules file is fixed and hashed (W0-T07; runs/RUN-keepkill-rules.json; GATE-schema fails if it changes).
// The browser never parses YAML: it applies this typed snapshot, whose RULES_SHA256 is the SHA-256 of the
// exact bytes it was generated from. An experiment-seed draw stores that hash, and every read refuses to run
// when the rules it applies hash to anything else (the rules' common.experiment_seed). The --check mode runs
// with the package's tests, so a snapshot that drifts from the file fails the fast lane.

import crypto from 'node:crypto'
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { parseYaml } from '../../ids/src/yaml-subset.ts'
import type { YamlValue } from '../../ids/src/yaml-subset.ts'

export const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..', '..')
export const RULES_PATH = 'content/governance/keepkill-rules.yaml'
export const OUT_PATH = 'packages/ledger/src/keepkill/rules.generated.ts'

type Obj = { [key: string]: YamlValue }
const isObj = (v: YamlValue | undefined): v is Obj => typeof v === 'object' && v !== null && !Array.isArray(v)

function need<T>(ok: boolean, value: T, what: string): T {
  if (!ok) throw new Error(`${RULES_PATH}: ${what}`)
  return value
}

const strings = (v: YamlValue | undefined, what: string): string[] =>
  need(Array.isArray(v) && v.every((x) => typeof x === 'string'), (v ?? []) as string[], `${what} must be a list of strings`)

/** The generated module for the given bytes of the rules file. */
export function render(bytes: Buffer): string {
  const sha256 = crypto.createHash('sha256').update(bytes).digest('hex')
  const doc = parseYaml(bytes.toString('utf8'))
  if (!isObj(doc)) throw new Error(`${RULES_PATH}: not a mapping`)
  const parameters = need(isObj(doc.parameters), doc.parameters as Obj, 'parameters must be a mapping')
  for (const [k, v] of Object.entries(parameters)) need(typeof v === 'number', v, `parameters.${k} must be a number`)
  const comparisons = need(Array.isArray(doc.comparisons), doc.comparisons as YamlValue[], 'comparisons must be a list')
  const kc: unknown[] = []
  let window: unknown = null
  for (const c of comparisons) {
    if (!isObj(c)) throw new Error(`${RULES_PATH}: a comparison must be a mapping`)
    const number = need(typeof c.number === 'number', c.number as number, 'a comparison needs a number')
    const id = need(typeof c.id === 'string', c.id as string, `comparison ${number} needs an id`)
    const arms = strings(c.arms, `comparison ${id}: arms`)
    need(arms.length === 2, arms, `comparison ${id} must have two arms`)
    const base = {
      number,
      id,
      arms,
      cheaperAlternative: need(typeof c.cheaper_alternative === 'boolean', c.cheaper_alternative as boolean, `comparison ${id}: cheaper_alternative`),
      contributingStages: strings(c.contributing_stages, `comparison ${id}: contributing_stages`),
    }
    if (isObj(c.units)) {
      const units: Record<string, string[]> = {}
      for (const [stratum, list] of Object.entries(c.units)) units[stratum] = strings(list, `comparison ${id}: units.${stratum}`)
      kc.push({ ...base, units, ...(c.families !== undefined ? { families: strings(c.families, `comparison ${id}: families`) } : {}) })
    } else {
      need(window === null, null, 'only one comparison may allocate windows')
      window = base
    }
  }
  need(window !== null, null, 'no window comparison')
  const json = (v: unknown): string => JSON.stringify(v, null, 2)
  return [
    '// GENERATED by packages/ledger/scripts/build-rules.ts from content/governance/keepkill-rules.yaml. Do not edit.',
    '// The rules file never changes (GATE-schema holds its SHA-256 to runs/RUN-keepkill-rules.json); an amendment',
    '// is a new file with its own record. Regenerate with: node packages/ledger/scripts/build-rules.ts',
    '',
    `export const RULES_PATH = ${json(RULES_PATH)}`,
    '',
    '/** The SHA-256 of the exact bytes this snapshot was generated from. A draw stores it; a read checks it. */',
    `export const RULES_SHA256 = ${json(sha256)}`,
    '',
    `export const RULES_VERSION = ${json(doc.version)}`,
    '',
    `export const RULES_FIXED_ON = ${json(doc.fixed_on)}`,
    '',
    '/** The rules\' parameters; every one is a design value [D] except z, the double nearest the 0.975 normal quantile. */',
    `export const PARAMETERS = ${json(parameters)} as const`,
    '',
    '/** Comparisons 1 to 3: units are KCs, listed by stage (the strata). */',
    `export const KC_COMPARISONS = ${json(kc)} as const`,
    '',
    '/** Comparison 4: units are 12-week windows, allocated in time order. */',
    `export const WINDOW_COMPARISON = ${json(window)} as const`,
    '',
  ].join('\n')
}

function main(): void {
  const bytes = fs.readFileSync(path.join(ROOT, RULES_PATH))
  const text = render(bytes)
  const out = path.join(ROOT, OUT_PATH)
  if (process.argv.includes('--check')) {
    const held = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : ''
    if (held !== text) {
      console.error(`${OUT_PATH} differs from a fresh generation from ${RULES_PATH}; run node packages/ledger/scripts/build-rules.ts`)
      process.exit(1)
    }
    console.log(`ok    ${OUT_PATH} equals a fresh generation from ${RULES_PATH}`)
    return
  }
  fs.writeFileSync(out, text)
  console.log(`wrote ${OUT_PATH}`)
}

if (process.argv[1] !== undefined && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main()
