// TypeScript emitter: types, the embedded schema documents and the statement-hash constants.

const IDENT = /^[A-Za-z_$][A-Za-z0-9_$]*$/;

/** Wrap prose into lines of at most `width` characters. */
export function wrap(text, width) {
  const lines = [];
  for (const paragraph of String(text).split('\n')) {
    let line = '';
    for (const word of paragraph.split(/\s+/).filter(Boolean)) {
      if (line && line.length + 1 + word.length > width) {
        lines.push(line);
        line = word;
      } else {
        line = line ? `${line} ${word}` : word;
      }
    }
    lines.push(line);
  }
  return lines;
}

function jsdoc(parts, indent) {
  const texts = parts.filter(Boolean);
  if (texts.length === 0) return [];
  const body = [];
  texts.forEach((t, i) => {
    if (i > 0) body.push('');
    body.push(...wrap(t.replaceAll('*/', '*\\/'), 100 - indent.length));
  });
  if (body.length === 1) return [`${indent}/** ${body[0]} */`];
  return [`${indent}/**`, ...body.map((l) => (l === '' ? `${indent} *` : `${indent} * ${l}`)), `${indent} */`];
}

const key = (k) => (IDENT.test(k) ? k : JSON.stringify(k));

export function tsType(node) {
  switch (node.t) {
    case 'prim':
      return node.prim === 'integer' ? 'number' : node.prim;
    case 'lit':
      return JSON.stringify(node.value);
    case 'ref':
      return node.name;
    case 'union':
      return node.items.map(tsType).join(' | ');
    case 'array': {
      const inner = tsType(node.item);
      return node.item.t === 'union' ? `(${inner})[]` : `${inner}[]`;
    }
    case 'tuple': {
      const rest = node.rest ? [`...${node.rest.t === 'union' ? `(${tsType(node.rest)})` : tsType(node.rest)}[]`] : [];
      return `[${[...node.items.map(tsType), ...rest].join(', ')}]`;
    }
    case 'record':
      return `Record<string, ${tsType(node.value)}>`;
    default:
      throw new Error(`cannot print ${JSON.stringify(node)}`);
  }
}

export const header = (digest, comment) =>
  `${comment} GENERATED by schemas/codegen/generate.mjs from schemas/*.schema.json. Do not edit by hand.\n` +
  `${comment} Regenerate with: node schemas/codegen/generate.mjs\n` +
  `${comment} schema-digest: ${digest}\n`;

export function emitTypes(model, digest) {
  const out = [header(digest, '//')];
  for (const d of model.decls) {
    if (d.kind === 'object') {
      out.push(...jsdoc([d.title, d.description], ''));
      out.push(`export interface ${d.name} {`);
      for (const p of d.props) {
        out.push(...jsdoc([p.description], '  '));
        out.push(`  ${key(p.key)}${p.optional ? '?' : ''}: ${tsType(p.type)};`);
      }
      if (d.open) out.push('  [key: string]: unknown;');
      out.push('}', '');
    } else {
      out.push(...jsdoc([d.title, d.description], ''));
      out.push(`export type ${d.name} = ${tsType(d.node)};`, '');
    }
  }
  out.push('/** Record types by the value of their `schema` field. */');
  out.push('export interface RecordTypes {');
  for (const r of model.records) out.push(`  ${JSON.stringify(r.schemaConst)}: ${r.typeName};`);
  out.push('}', '');
  out.push('/** The type each published schema describes, by schema name. */');
  out.push('export interface SchemaTypes {');
  for (const r of model.roots) out.push(`  ${JSON.stringify(r.name)}: ${r.typeName};`);
  out.push('}', '');
  return out.join('\n');
}

function indentBlock(text, spaces) {
  const pad = ' '.repeat(spaces);
  return text.split('\n').map((l, i) => (i === 0 ? l : pad + l)).join('\n');
}

export function emitSchemas(docs, model, digest) {
  const records = new Map(model.records.map((r) => [r.id, r.schemaConst]));
  const out = [header(digest, '//')];
  out.push('export interface SchemaDocument {');
  out.push('  /** The file name without .schema.json. */');
  out.push('  readonly name: string;');
  out.push('  /** The $id of the document, urn:statespace:<name>@<major>. */');
  out.push('  readonly id: string;');
  out.push('  /** The value of the record\'s `schema` field, or null for a document of shared definitions. */');
  out.push('  readonly schema: string | null;');
  out.push('  /** The schema, as parsed JSON. */');
  out.push('  readonly json: Readonly<Record<string, unknown>>;');
  out.push('}', '');
  out.push(`export const SCHEMA_DIGEST = ${JSON.stringify(digest)};`, '');
  out.push('export const SCHEMA_DOCUMENTS: readonly SchemaDocument[] = [');
  for (const d of docs) {
    out.push('  {');
    out.push(`    name: ${JSON.stringify(d.name)},`);
    out.push(`    id: ${JSON.stringify(d.doc.$id)},`);
    out.push(`    schema: ${JSON.stringify(records.get(d.doc.$id) ?? null)},`);
    out.push(`    json: ${indentBlock(JSON.stringify(d.doc, null, 2), 4)},`);
    out.push('  },');
  }
  out.push('];', '');
  return out.join('\n');
}

export function emitStatementHashSpec(spec, digest) {
  const out = [header(digest, '//')];
  out.push(`export const STATEMENT_HASH_SPEC_ID = ${JSON.stringify(spec.id)};`, '');
  out.push('/**');
  out.push(' * The code points that trimRight removes from the end of a statement, in ascending order. All are in');
  out.push(' * the Basic Multilingual Plane, so trimming UTF-16 code units is exact. The one written source is');
  out.push(' * x-statementHash in schemas/defs.schema.json.');
  out.push(' */');
  out.push('export const TRIM_RIGHT_CODE_POINTS: readonly number[] = [');
  for (const c of spec.codePoints) out.push(`  0x${c.value.toString(16).toUpperCase().padStart(4, '0')}, // ${c.name}`);
  out.push('];', '');
  return out.join('\n');
}
