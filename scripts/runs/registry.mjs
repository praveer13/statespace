// The runs registry, shared by GATE-runs (scripts/verify-runs.mjs), the index builder and the recording
// scripts in this folder. Dependency-free.

import crypto from 'node:crypto';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

export const HERE = path.dirname(fileURLToPath(import.meta.url));
export const REPO = path.resolve(HERE, '..', '..');

export const RUN_ID = /^RUN-[a-z0-9]+(?:-[a-z0-9]+)*$/;
const RUN_ID_IN_TEXT = /RUN-[a-z0-9]+(?:-[a-z0-9]+)*/g;
/** The format placeholders that documents write in code spans when they describe the reference forms. */
export const PLACEHOLDER_IDS = new Set(['ID', 'RUN-id', 'RUN-ID', 'RUN-<id>', 'RUN-…', 'RUN-...', 'RUN-{kebab}', 'RUN-x', 'id']);
/**
 * {{run:}} with no ID names the reference form itself, and RUN-id and ID are the spine's own names for the
 * format: neither is a reference, in prose or in code.
 */
export const isFormMention = (ref) => (ref.form === 'template' && ref.id === '') || ref.id === 'RUN-id' || ref.id === 'ID';
/** The core fields of run@1 that may be null; an imported record names each null one in unrecorded. */
export const NULLABLE_CORE = ['binary', 'binary_sha256', 'image', 'started_at', 'duration_s', 'argv', 'exit_code'];
export const NULLABLE_ENVIRONMENT = ['os', 'cpu_count', 'ram_gib', 'cpu_architecture'];

// ------------------------------------------------------------------ files and hashes
export const sha256 = (bytes) => crypto.createHash('sha256').update(bytes).digest('hex');
export const sha256File = (file) => sha256(fs.readFileSync(file));
export const posix = (p) => p.split(path.sep).join('/');
/** A path outside the repository: <sandbox>/..., <scratch>/... */
export const isPlaceholderPath = (p) => typeof p === 'string' && p.startsWith('<');

/** {path, sha256, bytes} of a repository file, path relative to root. */
export function fileRecord(root, rel, extra = {}) {
  const abs = path.join(root, rel);
  const bytes = fs.readFileSync(abs);
  return { path: posix(rel), sha256: sha256(bytes), bytes: bytes.length, ...extra };
}

// ------------------------------------------------------------------ the registry
/** Every runs/RUN-*.json under root: [{file, id, doc, error}]. */
export function loadRegistry(root) {
  const dir = path.join(root, 'runs');
  if (!fs.existsSync(dir)) return [];
  return fs
    .readdirSync(dir)
    .filter((f) => /^RUN-.*\.json$/.test(f))
    .sort()
    .map((f) => {
      const file = `runs/${f}`;
      const id = f.replace(/\.json$/, '');
      try {
        return { file, id, doc: JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8')), error: null };
      } catch (e) {
        return { file, id, doc: null, error: e instanceof Error ? e.message : String(e) };
      }
    });
}

/** The index of the registry: one line per record, with the hash of the record file. */
export function buildIndex(root) {
  const runs = loadRegistry(root).map(({ file, id, doc }) => ({
    id,
    title: doc?.title ?? null,
    engine: doc?.engine ?? null,
    version: doc?.version ?? null,
    task: doc?.task ?? null,
    origin: doc?.origin ?? 'recorded',
    started_at: doc?.started_at ?? null,
    recorded_at: doc?.recorded_at ?? null,
    sha256: sha256File(path.join(root, file)),
  }));
  return {
    description:
      'The index of the runs registry: one entry per runs/RUN-*.json, with the SHA-256 of the record file. Generated by node scripts/runs/build-index.mjs; GATE-runs reports it as stale when a record is added or changed (the release lane fails on that).',
    count: runs.length,
    runs,
  };
}

export const indexText = (root) => `${JSON.stringify(buildIndex(root), null, 2)}\n`;

// ------------------------------------------------------------------ references in documents and copy
/** Inline code spans of a line, as [start, end) ranges. */
function codeRanges(line) {
  const ranges = [];
  const re = /(`+)([\s\S]*?[^`])\1(?!`)/g;
  let m;
  while ((m = re.exec(line)) !== null) ranges.push([m.index, m.index + m[0].length]);
  return ranges;
}

/**
 * The run references in a text: [{form: 'tag'|'template', id, path, line, column, inCode}].
 *   tag       [X RUN-a] or [X RUN-a, RUN-b, ...]: claims an executed run on disk
 *   template  {{run:ID}} or {{run:ID#dotted.path}}: a run that must be recorded before the sentence ships
 * Fenced code blocks are read too: a reference there is still a reference, unless it is a placeholder.
 */
export function referencesOf(text) {
  const out = [];
  const lines = text.replaceAll('\r\n', '\n').split('\n');
  let fenced = false;
  lines.forEach((line, i) => {
    if (/^\s*(```|~~~)/.test(line)) {
      fenced = !fenced;
      return;
    }
    const code = codeRanges(line);
    const inCode = (at) => fenced || code.some(([a, b]) => at >= a && at < b);
    for (const m of line.matchAll(/\[X\s+([^\]]*)\]/g)) {
      for (const id of m[1].matchAll(RUN_ID_IN_TEXT)) {
        const at = m.index + 3 + id.index;
        out.push({ form: 'tag', id: id[0], path: null, line: i + 1, column: at + 1, inCode: inCode(m.index) });
      }
    }
    for (const m of line.matchAll(/\{\{run:([^}#]*)(?:#([^}]*))?\}\}/g)) {
      out.push({ form: 'template', id: m[1].trim(), path: m[2] ?? null, line: i + 1, column: m.index + 1, inCode: inCode(m.index) });
    }
  });
  return out;
}

/** Whether a document labels itself a draft: "draft: first-learner pass pending" in its status line or front matter. */
export function isDraft(text, file) {
  const head = text.replaceAll('\r\n', '\n').split('\n').slice(0, 40);
  if (/\.ya?ml$/.test(file)) return head.some((l) => /^(?:status:\s*["']?draft\b|draft:\s*true\b)/i.test(l.trim()));
  if (head[0]?.trim() === '---') {
    const end = head.indexOf('---', 1);
    if (end > 0 && head.slice(1, end).some((l) => /^(?:status:\s*["']?draft\b|draft:\s*true\b)/i.test(l.trim()))) return true;
  }
  return head.some((l) => /^(?:>\s*)?(?:\*\*)?Status:?(?:\*\*)?:?\s*(?:\*\*)?draft\b/i.test(l.trim()));
}

/** Resolve a dotted path (values.foo, configs.0.argv) inside a record; undefined when it names nothing. */
export function resolvePath(doc, dotted) {
  let v = doc;
  for (const part of dotted.split('.')) {
    if (v === null || typeof v !== 'object') return undefined;
    v = Array.isArray(v) ? v[Number(part)] : v[part];
  }
  return v;
}

// ------------------------------------------------------------------ the environment of a recording
/** The host as a run record states it. */
export function hostEnvironment() {
  return {
    os: `${os.type()} ${os.release()}`,
    cpu_count: os.cpus().length,
    ram_gib: Math.round((os.totalmem() / 2 ** 30) * 10) / 10,
    cpu_architecture: os.arch() === 'x64' ? 'x86_64' : os.arch(),
  };
}

/** Replace private absolute paths with repository-relative paths or placeholders (rule: no private paths). */
export function normalizePaths(text, { root = REPO, sandbox = [] } = {}) {
  let out = String(text);
  for (const s of sandbox) if (s) out = out.split(s).join('<sandbox>');
  out = out.split(`${root}/`).join('').split(root).join('.');
  const home = os.homedir();
  if (home && home !== '/') out = out.split(home).join('<home>');
  return out;
}
