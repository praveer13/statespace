"""W0-S09: record the seeded GEN-anomaly-id grid on PostgreSQL 18.6.

Every cell of every pattern (patterns.py) is rendered to an isolationtester spec
and run; each permutation the tester prints is one recorded history. The histories
are written, verbatim, to content/pg-catalog/grid/<template>.ndjson with a compact
reading of each; the grid's definition, counts and checks go to grid/grid.json and
runs/RUN-pg-catalog/grid-run.json. Everything runs twice and a history that differs
between the passes is left out of the pool.

usage (from the repository root):
  python3 -I scripts/spikes/W0-S09/run_grid.py [--only pattern[,pattern]] [--passes 2]
"""
