def render_row(row):
    """The text of one row's spec, and its permutation count per level."""
    uses_seen = row["pattern"] in ("rmw2", "teamsum2", "holds2")
    header = row["head"] + [""] + COMMON + (SEEN if uses_seen else []) + ["", "Canonical numbers: " + ", ".join(
        f"{k} {v}" for k, v in row["cell"].items())]
    return P.render_multilevel(row["pattern"], row["cell"], header, row["headline"])


def main():
    for row in ROWS:
        text, counts = render_row(row)
        path = os.path.join(OUT, row["file"])
        with open(path, "w", encoding="utf-8") as fh:
            fh.write(text)
        print(f"{row['file']}: permutations per level {counts}")


if __name__ == "__main__":
    main()
